import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../public/vitame/home-calendar.js',import.meta.url),'utf8');
const handlers={},settles=[];let captured=true;
const frame={setPointerCapture(){},hasPointerCapture:()=>captured};
const context={document:{addEventListener:(name,fn)=>{(handlers[name]||=[]).push(fn);}},window:{addEventListener(){}},performance:{now:()=>100},frame,settles};
vm.createContext(context);
vm.runInContext(source.slice(0,source.indexOf('let calendarOpen =')),context);
vm.runInContext(`prepareSlide=(element,adapter)=>({element,adapter,width:400});mountSlide=s=>s.frame=frame;moveSlide=()=>{};settleSlide=(s,d)=>{s.settling=true;settles.push(d);};slideAdapters.push({selector:'.calendar-surface'});`,context);
const target={closest:selector=>selector==='.calendar-surface'?target:null};
const event=(x,y)=>({button:0,isPrimary:true,pointerId:1,clientX:x,clientY:y,target,stopImmediatePropagation(){},preventDefault(){}});
handlers.pointerdown[0](event(200,100));
handlers.pointermove[0](event(188,113));
assert.equal(vm.runInContext('liveSlide.active',context),true,'slightly diagonal touch starts horizontal drag');
handlers.lostpointercapture[0]({...event(188,113),target});
assert.equal(settles.length,0,'implicit capture transfer must not cancel swipe');
handlers.lostpointercapture[0]({...event(188,113),target:frame});
assert.equal(settles.length,0,'retained frame capture does not cancel');
handlers.pointerup[0](event(80,113));
assert.equal(settles.at(-1),1,'touch release advances calendar');
vm.runInContext('liveSlide=null',context);
handlers.pointerdown[0](event(200,100));handlers.pointermove[0](event(197,125));
assert.equal(vm.runInContext('liveSlide',context),null,'vertical page scroll remains available');
console.log('Calendar touch: diagonal swipe, implicit capture transfer, release and vertical scroll passed.');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../public/vitame/home-calendar.js',import.meta.url),'utf8');
const context={};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function calendarReturnOffsets('),source.indexOf('function returnCalendarToToday(')),context);
const offsets=(from,to,monthly)=>Array.from(context.calendarReturnOffsets(new Date(from+'T12:00:00'),new Date(to+'T12:00:00'),monthly));
assert.deepEqual(offsets('2026-07-01','2026-10-16',true),[1,2,3]);
assert.deepEqual(offsets('2027-01-01','2026-10-16',true),[-1,-2,-3]);
assert.deepEqual(offsets('2026-10-01','2026-10-16',true),[]);
assert.deepEqual(offsets('2026-10-02','2026-10-16',false),[1,2]);
assert.deepEqual(offsets('2026-10-30','2026-10-16',false),[-1,-2]);
assert.deepEqual(offsets('2026-10-11','2026-10-16',false),[]);
const distant=offsets('2020-01-01','2026-10-16',true);
assert.equal(distant.length,8);assert.equal(distant.at(-1),81);
assert.match(source,/adapter\.preview\(offset\)/);
assert.match(source,/prefers-reduced-motion: reduce/);
console.log('Calendar rewind: weekly/monthly pages, both directions, same period and bounded long-distance return passed.');

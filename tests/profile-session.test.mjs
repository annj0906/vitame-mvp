import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../public/vitame/app.js',import.meta.url),'utf8');
const snippet=source.slice(source.indexOf('const initial='),source.indexOf('const dateKey='));
let stored=JSON.stringify({name:'이전 이름',profileCharacter:'very-good',records:{keep:true},supplements:[{id:'s1'}]});
const context=()=>vm.createContext({localStorage:{getItem:()=>stored,setItem:(key,value)=>{stored=value;}},toast(){}});
const ctx=context();vm.runInContext(snippet,ctx);
assert.equal(vm.runInContext('state.name',ctx),'서연');
assert.equal(vm.runInContext('state.profileCharacter',ctx),'good');
vm.runInContext("state.name='수정 이름';state.profileCharacter='bad';save()",ctx);
assert.equal(vm.runInContext('state.name',ctx),'수정 이름');
assert.equal(JSON.parse(stored).name,undefined);
assert.equal(JSON.parse(stored).profileCharacter,undefined);
assert.deepEqual(JSON.parse(stored).records,{keep:true});
assert.deepEqual(JSON.parse(stored).supplements,[{id:'s1'}]);
const reloaded=context();vm.runInContext(snippet,reloaded);
assert.equal(vm.runInContext('state.name',reloaded),'서연');
assert.equal(vm.runInContext('state.profileCharacter',reloaded),'good');
console.log('Profile: session-only edits, Seoyeon/purple defaults on reload, other records preserved.');
